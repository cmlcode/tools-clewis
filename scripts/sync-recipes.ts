// scripts/sync-recipes.ts
// Builds a SQL file that makes prod's food recipes match your local dev database: new recipes are
// inserted and existing ones (matched by SLUG, the recipe's web address) are updated, along with
// their ingredients and steps. It never deletes a recipe, and it never touches photos.
//
// Usage:
//   npx tsx scripts/sync-recipes.ts                                          # reads local RECIPES_DB, writes sync-recipes.sql
//   npx wrangler d1 execute RECIPES_DB --remote --file=sync-recipes.sql      # review the file first
//
// Good to know:
//  - Ingredients and steps of a recipe that exists locally are REPLACED in prod (removed, then re-added
//    from local), because that is the only way a deleted or reordered line carries over.
//  - A recipe you delete locally stays in prod. Delete it there from the site.
//  - Photos live in R2, not in the database, so they are not synced. Upload them on the real site.
//  - The slug is the identity. Renaming a recipe's title keeps its slug, so it updates in place.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

export interface RecipeRow {
  id: number;
  slug: string;
  title: string;
  category: string;
  cook_minutes: number;
  servings: number;
  tint: string;
}
export interface IngredientRow {
  recipe_id: number;
  position: number;
  qty: number | null;
  unit: string | null;
  name: string;
}
export interface StepRow {
  recipe_id: number;
  position: number;
  phase: string;
  body: string;
  minutes: number | null;
}

const q = (v: string | null | undefined) => (v == null ? "NULL" : `'${v.replace(/'/g, "''")}'`);
const n = (v: number | null | undefined) => (v == null ? "NULL" : String(v));

function query<T>(sql: string): T[] {
  const out = execFileSync(
    "npx",
    ["wrangler", "d1", "execute", "RECIPES_DB", "--local", "--json", "--command", sql],
    { encoding: "utf8", maxBuffer: 50 * 1024 * 1024 }
  );
  return JSON.parse(out)[0].results as T[];
}

export function buildSql(recipes: RecipeRow[], ingredients: IngredientRow[], steps: StepRow[]): string {
  const slugs = new Set(recipes.map((r) => r.slug));
  if (slugs.size !== recipes.length) throw new Error("Two local recipes share a slug.");

  const sql: string[] = ["-- Generated by scripts/sync-recipes.ts. Review before running with --remote.", ""];
  for (const r of [...recipes].sort((a, b) => a.slug.localeCompare(b.slug))) {
    const id = `(SELECT id FROM recipes WHERE slug = ${q(r.slug)})`;

    sql.push(`-- ${r.title}`);
    // 1) create it if prod doesn't have it yet
    sql.push(
      `INSERT INTO recipes (slug, title, category, cook_minutes, servings, tint) ` +
        `SELECT ${q(r.slug)}, ${q(r.title)}, ${q(r.category)}, ${n(r.cook_minutes)}, ${n(r.servings)}, ${q(r.tint)} ` +
        `WHERE NOT EXISTS (SELECT 1 FROM recipes WHERE slug = ${q(r.slug)});`
    );
    // 2) bring the recipe's own fields in line with local (this is what carries edits over)
    sql.push(
      `UPDATE recipes SET title = ${q(r.title)}, category = ${q(r.category)}, cook_minutes = ${n(r.cook_minutes)}, ` +
        `servings = ${n(r.servings)}, tint = ${q(r.tint)}, updated_at = datetime('now') WHERE slug = ${q(r.slug)};`
    );
    // 3) replace its ingredients and steps with local's
    sql.push(`DELETE FROM recipe_ingredients WHERE recipe_id = ${id};`);
    for (const i of ingredients.filter((x) => x.recipe_id === r.id).sort((a, b) => a.position - b.position)) {
      sql.push(
        `INSERT INTO recipe_ingredients (recipe_id, position, qty, unit, name) ` +
          `SELECT id, ${n(i.position)}, ${n(i.qty)}, ${q(i.unit)}, ${q(i.name)} FROM recipes WHERE slug = ${q(r.slug)};`
      );
    }
    sql.push(`DELETE FROM recipe_steps WHERE recipe_id = ${id};`);
    for (const s of steps.filter((x) => x.recipe_id === r.id).sort((a, b) => a.position - b.position)) {
      sql.push(
        `INSERT INTO recipe_steps (recipe_id, position, phase, body, minutes) ` +
          `SELECT id, ${n(s.position)}, ${q(s.phase)}, ${q(s.body)}, ${n(s.minutes)} FROM recipes WHERE slug = ${q(r.slug)};`
      );
    }
    sql.push("");
  }
  return sql.join("\n");
}

function main() {
  const recipes = query<RecipeRow>("SELECT id, slug, title, category, cook_minutes, servings, tint FROM recipes");
  const ingredients = query<IngredientRow>("SELECT recipe_id, position, qty, unit, name FROM recipe_ingredients");
  const steps = query<StepRow>("SELECT recipe_id, position, phase, body, minutes FROM recipe_steps");

  writeFileSync("sync-recipes.sql", buildSql(recipes, ingredients, steps));
  console.log(`Wrote sync-recipes.sql for ${recipes.length} recipes. Review it, then:`);
  console.log("  npx wrangler d1 execute RECIPES_DB --remote --file=sync-recipes.sql");
}

// Only run when started directly (npx tsx scripts/sync-recipes.ts), not when a test imports buildSql.
if (process.argv[1]?.endsWith("sync-recipes.ts")) main();
