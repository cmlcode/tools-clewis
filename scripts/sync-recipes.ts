// scripts/sync-recipes.ts
// Builds a SQL file that makes prod's recipes match your local dev database: new drinks are
// inserted and existing ones (matched by NAME) are updated. It never deletes anything.
//
// Usage:
//   npx tsx scripts/sync-recipes.ts                 # reads local BAR_DB, writes sync-recipes.sql
//   wrangler d1 execute BAR_DB --remote --file=sync-recipes.sql   # review the file first
//
// Optional: --input recipes.json (a saved `SELECT * FROM recipes` result) instead of reading local D1.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

interface Row {
  id: number;
  name: string;
  description: string | null;
  ingredients: string;
  instructions: string | null;
  family: string | null;
  parent_id: number | null;
  changes: string | null;
}

const COLS = "id, name, description, ingredients, instructions, family, parent_id,changes";
const q = (v: string | null | undefined) => (v == null ? "NULL" : `'${v.replace(/'/g, "''")}'`);

function readRows(): Row[] {
  const i = process.argv.indexOf("--input");
  if (i !== -1) {
    const data = JSON.parse(readFileSync(process.argv[i + 1], "utf8"));
    return (Array.isArray(data) && data[0]?.results ? data[0].results : data) as Row[];
  }
  const out = execFileSync(
    "npx",
    ["wrangler", "d1", "execute", "BAR_DB", "--local", "--json", "--command", `SELECT ${COLS} FROM recipes`],
    { encoding: "utf8", maxBuffer: 50 * 1024 * 1024 }
  );
  return JSON.parse(out)[0].results as Row[];
}

/** Parents before their variations, so each parent exists in prod when a child refers to it. */
function parentsFirst(rows: Row[]): Row[] {
  const byId = new Map(rows.map((r) => [r.id, r]));
  const done = new Set<number>();
  const out: Row[] = [];
  const visit = (r: Row, trail: Set<number>) => {
    if (done.has(r.id) || trail.has(r.id)) return;
    trail.add(r.id);
    const p = r.parent_id === null ? undefined : byId.get(r.parent_id);
    if (p) visit(p, trail);
    done.add(r.id);
    out.push(r);
  };
  [...rows].sort((a, b) => a.name.localeCompare(b.name)).forEach((r) => visit(r, new Set()));
  return out;
}

function main() {
  const rows = readRows();
  const names = new Set(rows.map((r) => r.name.toLowerCase()));
  if (names.size !== rows.length) {
    console.error("Two local drinks share a name (ignoring case). Names must be unique to sync by name.");
    process.exit(1);
  }
  const nameOf = new Map(rows.map((r) => [r.id, r.name]));

  const sql: string[] = ["-- Generated by scripts/sync-recipes.ts. Review before running with --remote.", ""];
  for (const r of parentsFirst(rows)) {
    const parent =
      r.parent_id === null || !nameOf.has(r.parent_id)
        ? "NULL"
        : `(SELECT id FROM recipes WHERE name = ${q(nameOf.get(r.parent_id))} COLLATE NOCASE)`;
    const where = `name = ${q(r.name)} COLLATE NOCASE`;

    // 1) create it if prod doesn't have it yet
    sql.push(
      `INSERT INTO recipes (name, ingredients) SELECT ${q(r.name)}, '' WHERE NOT EXISTS (SELECT 1 FROM recipes WHERE ${where});`
    );
    // 2) bring every field in line with local (this is what carries edits over)
    sql.push(
      `UPDATE recipes SET description = ${q(r.description ?? "")}, ingredients = ${q(r.ingredients)}, ` +
        `instructions = ${q(r.instructions ?? "")}, family = ${q(r.family)}, parent_id = ${parent}, ` +
        `changes = ${q(r.changes ?? "[]")} WHERE ${where};`,
      ""
    );
  }

  writeFileSync("sync-recipes.sql", sql.join("\n"));
  console.log(`Wrote sync-recipes.sql for ${rows.length} drinks. Review it, then:`);
  console.log("  wrangler d1 execute BAR_DB --remote --file=sync-recipes.sql");
}

main();
